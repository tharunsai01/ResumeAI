interface SampleOffer {
  candidate: string
  company: string
  position: string
  hiringDate: string
  reference: string
}

export async function downloadSampleOfferLetter(offer: SampleOffer) {
  const { PDFDocument, StandardFonts, rgb } = await import("pdf-lib")
  const document = await PDFDocument.create()
  document.setTitle("HireSmart AI | Sample Offer Letter")
  const page = document.addPage([595, 842])
  const regular = await document.embedFont(StandardFonts.Helvetica)
  const bold = await document.embedFont(StandardFonts.HelveticaBold)
  const serif = await document.embedFont(StandardFonts.TimesRomanBold)
  const navy = rgb(0.08, 0.13, 0.24)
  const indigo = rgb(0.29, 0.22, 0.74)
  const muted = rgb(0.32, 0.37, 0.47)

  const text = (value: string, x: number, y: number, size: number, font = regular, color = navy, maxWidth = 480) => {
    const charset = new Set(font.getCharacterSet())
    const printable = Array.from(value.replace(/\s+/g, " "), char => {
      if (charset.has(char.codePointAt(0)!)) return char
      return Array.from(char.normalize("NFKD")).filter(letter => charset.has(letter.codePointAt(0)!)).join("") || "?"
    }).join("")
    page.drawText(printable, { x, y, size, font, color, maxWidth, lineHeight: size * 1.45 })
  }

  page.drawRectangle({ x: 0, y: 726, width: 595, height: 116, color: navy })
  page.drawRectangle({ x: 56, y: 768, width: 34, height: 34, color: indigo })
  text("H", 66, 777, 21, bold, rgb(1, 1, 1), 24)
  text("HireSmart AI", 103, 779, 16, bold, rgb(1, 1, 1))
  text("DEMONSTRATION COPY", 390, 779, 9, bold, rgb(0.82, 0.81, 1))

  text("Sample Offer Letter", 56, 662, 38, serif)
  text(offer.hiringDate, 57, 629, 11, regular, muted)
  page.drawLine({ start: { x: 56, y: 607 }, end: { x: 539, y: 607 }, thickness: 1, color: indigo })

  text(`Dear ${offer.candidate},`, 56, 572, 13, bold)
  text(`Congratulations on being selected for the ${offer.position} role at ${offer.company}. Thank you for taking the time to meet with the hiring team.`, 56, 535, 13)
  page.drawRectangle({ x: 56, y: 318, width: 483, height: 122, color: rgb(0.95, 0.95, 0.99) })
  text("POSITION", 73, 414, 9, bold, indigo)
  text(offer.position, 73, 393, 12, bold, navy, 448)
  text("EMPLOYER", 73, 360, 9, bold, indigo)
  text(offer.company, 73, 339, 12, bold, navy, 448)

  text("The hiring team will provide the official offer, employment terms, and next steps.", 56, 272, 13)
  text("Best wishes,", 56, 211, 12)
  text(offer.company, 56, 190, 12, bold)

  page.drawLine({ start: { x: 56, y: 105 }, end: { x: 539, y: 105 }, thickness: 1, color: rgb(0.83, 0.85, 0.91) })
  text("Generated by HireSmart AI  |  Sample only", 56, 81, 10, bold, muted)
  text(`Application reference  ${offer.reference}`, 56, 61, 9, regular, muted)

  const bytes = await document.save()
  const url = URL.createObjectURL(new Blob([new Uint8Array(bytes)], { type: "application/pdf" }))
  const link = window.document.createElement("a")
  link.href = url
  link.download = "HireSmart-AI-Sample-Offer-Letter.pdf"
  link.click()
  window.setTimeout(() => URL.revokeObjectURL(url), 30_000)
}
